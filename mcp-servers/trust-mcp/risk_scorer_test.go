func TestHeuristicScorerDoesNotFlagAnOrdinaryCounterBid(t *testing.T) {
	// A bids, B outbids, A counters: exactly 3 manual bids from 2 buyers.
	// This is completely ordinary competitive bidding, not a sustained
	// ping-pong pattern -- it must not be flagged.
	s := NewHeuristicScorer()
	got, err := s.ScoreBidRisk(context.Background(), BidRiskInput{
		BuyerID:           "buyer-1",
		AmountCents:       1500,
		ListingPriceCents: 1000,
		BidHistory: []fixtures.Bid{
			{BuyerID: "buyer-1", AmountCents: 1000},
			{BuyerID: "buyer-2", AmountCents: 1200},
		},
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Score != 0 {
		t.Fatalf("expected zero risk for an ordinary first counter-bid, got %+v", got)
	}
}

func TestHeuristicScorerIgnoresAutoGeneratedBidsForPingPongSignal(t *testing.T) {
	// The proxy-bidding engine legitimately produces rapid back-and-forth
	// auto-bids between two ceiling-holders -- that pattern must not be
	// flagged, or every normal auction with two engaged bidders would trip
	// the ping-pong signal.
	s := NewHeuristicScorer()
	got, err := s.ScoreBidRisk(context.Background(), BidRiskInput{
		BuyerID:           "buyer-3",
		AmountCents:       4000,
		ListingPriceCents: 1000,
		BidHistory: []fixtures.Bid{
			{BuyerID: "buyer-1", AmountCents: 1500, IsAutoBid: true},
			{BuyerID: "buyer-2", AmountCents: 2000, IsAutoBid: true},
			{BuyerID: "buyer-1", AmountCents: 2500, IsAutoBid: true},
			{BuyerID: "buyer-2", AmountCents: 3000, IsAutoBid: true},
		},
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Score != 0 {
		t.Fatalf("expected zero risk when the prior back-and-forth was all system-generated auto-bids, got %+v", got)
	}
}

func TestHeuristicScorerCapsScoreAtOne(t *testing.T) {
	s := NewHeuristicScorer()
	got, err := s.ScoreBidRisk(context.Background(), BidRiskInput{
		BuyerID:           "buyer-1",
		AmountCents:       5000,
		ListingPriceCents: 1000,
		BidHistory: []fixtures.Bid{
			{BuyerID: "buyer-1", AmountCents: 2000},
			{BuyerID: "buyer-2", AmountCents: 3000},
			{BuyerID: "buyer-1", AmountCents: 4000},
		},
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Score > 1.0 {
		t.Fatalf("expected score capped at 1.0, got %f", got.Score)
	}
}

func TestHeuristicScorerNoHistoryIsZeroRisk(t *testing.T) {
	s := NewHeuristicScorer()
	got, err := s.ScoreBidRisk(context.Background(), BidRiskInput{
		BuyerID: "buyer-1", AmountCents: 1000, ListingPriceCents: 1000,
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Score != 0 || len(got.Reasons) != 0 {
		t.Fatalf("expected zero risk and no reasons for a first bid with no history, got %+v", got)
	}
}
