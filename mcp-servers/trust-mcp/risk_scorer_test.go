package main

import (
	"context"
	"testing"

	"github.com/day0ops/marketplace-demo/fixtures"
)

func TestHeuristicScorerFlagsSelfBidding(t *testing.T) {
	s := NewHeuristicScorer()
	got, err := s.ScoreBidRisk(context.Background(), BidRiskInput{
		BuyerID:           "buyer-1",
		AmountCents:       2000,
		ListingPriceCents: 1000,
		BidHistory: []fixtures.Bid{
			{BuyerID: "buyer-1", AmountCents: 1500},
		},
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Score < 0.5 {
		t.Fatalf("expected a meaningful risk score for self-bidding, got %+v", got)
	}
	if len(got.Reasons) == 0 {
		t.Fatalf("expected at least one reason, got none")
	}
	if got.ScoredBy != "heuristic" {
		t.Fatalf("expected ScoredBy=heuristic, got %q", got.ScoredBy)
	}
}

